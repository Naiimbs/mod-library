// Regenerates projects/demo/src/app/app.routes.ts from the folders in
// projects/demo/src/app/pages. Each page lives at pages/<name>/<name>.page.ts
// and exports a class named <PascalName>Page.
//
//   node tools/gen-routes.mjs
import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pagesDir = join(root, 'projects/demo/src/app/pages');

const pascal = (s) => s.replace(/(^|-)(\w)/g, (_, __, c) => c.toUpperCase());
const title = (s) => s.replace(/-/g, ' ').replace(/^\w/, (c) => c.toUpperCase());

const names = readdirSync(pagesDir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && existsSync(join(pagesDir, d.name, `${d.name}.page.ts`)))
  .map((d) => d.name)
  .sort();

const first = ['components-overview', 'button'].find((n) => names.includes(n)) ?? names[0];
const lines = names.map(
  (n) =>
    `  {\n    path: '${n}',\n    title: '${title(n)}',\n    loadComponent: () => import('./pages/${n}/${n}.page').then((m) => m.${pascal(n)}Page),\n  },`,
);

writeFileSync(
  join(root, 'projects/demo/src/app/app.routes.ts'),
  `// Generated by tools/gen-routes.mjs — do not edit by hand.\nimport { Routes } from '@angular/router';\n\nexport const routes: Routes = [\n${lines.join('\n')}\n  { path: '', pathMatch: 'full', redirectTo: '${first}' },\n  { path: '**', redirectTo: '${first}' },\n];\n`,
);
console.log(`Wrote ${names.length} routes`);

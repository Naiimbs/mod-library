// Adds dark-mode text rules to the component stylesheets.
//
// In the MOD theme --sa-700 / --sa-800 are dark greens (the brand dark green
// and its shades). They are right as fills, but as a TEXT colour they vanish
// on dark-mode surfaces. For every component rule that uses one of them (or
// the tokens that alias them) as `color`, this script inserts a dark-mode
// twin directly after it that lifts the text to a light green.
//
// The twin uses :where() for the dark-mode prefix, so it has exactly the
// specificity of the rule it follows: later state rules in the same file
// (selected, disabled, on-color, …) keep winning as they do in light mode.
//
//   node tools/gen-dark-text.mjs        (re-run after changing component CSS)
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import postcss from 'postcss';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const libDir = join(root, 'projects/ui/src/lib');
const MARK = 'mod:dark-text (generated by tools/gen-dark-text.mjs)';
const PREFIX = ':where(html[data-theme="dark"])';

// hover-level text -> sa-300, pressed-level text -> the light sa-200 value
// (a literal, because --sa-200 itself is flipped to a dark tint in dark mode).
const LIFT = new Map([
  ['var(--sa-700)', 'var(--sa-300)'],
  ['var(--color-primary-hover)', 'var(--sa-300)'],
  ['var(--sa-800)', '#a3e6c6'],
  ['var(--color-primary-active)', '#a3e6c6'],
]);

function cssFiles(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) return cssFiles(full);
    return entry.name.endsWith('.css') ? [full] : [];
  });
}

let total = 0;
for (const file of cssFiles(libDir).sort()) {
  const source = readFileSync(file, 'utf8');
  const tree = postcss.parse(source, { from: file });

  // Remove twins from a previous run.
  tree.walkComments((comment) => {
    if (comment.text !== MARK) return;
    const next = comment.next();
    if (next && next.type === 'rule') next.remove();
    comment.remove();
  });

  const targets = [];
  tree.walkDecls('color', (decl) => {
    const lifted = LIFT.get(decl.value.replace(/\s*!important\s*$/, '').trim());
    const rule = decl.parent;
    if (!lifted || rule.type !== 'rule' || rule.selector.includes('[data-theme')) return;
    targets.push({ rule, lifted });
  });

  for (const { rule, lifted } of targets) {
    const twin = postcss.rule({
      selectors: rule.selectors.map((s) => `${PREFIX} ${s.trim()}`),
      raws: { before: '\n' + (rule.raws.before ?? '').replace(/^[\s\S]*\n/, ''), between: ' ', semicolon: true },
    });
    twin.append({ prop: 'color', value: lifted });
    rule.after(twin);
    rule.after(postcss.comment({ text: MARK, raws: { before: '\n\n' + (rule.raws.before ?? '').replace(/^[\s\S]*\n/, '') } }));
  }

  const output = tree.toString();
  if (output !== source) writeFileSync(file, output);
  if (targets.length) {
    console.log(`${relative(libDir, file).replace(/\\/g, '/')}: ${targets.length}`);
    total += targets.length;
  }
}
console.log(`dark-text twins: ${total}`);
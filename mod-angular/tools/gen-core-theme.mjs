// Writes projects/ui/src/styles/utilities/DGATheme.core.css: the vendored base
// theme reduced to the rules a library component can match.
//
// DGATheme.css is about 190 kB. Most of it is utility classes (.text-*,
// .background-*, .border-*, ...) and widget styles that no component uses.
// mod.css keeps the whole file, so applications that use those utility classes
// keep working. mod-core.css loads this reduced copy instead, for applications
// that only use the components and need a smaller initial bundle.
//
// A rule is kept when every class in at least one of its selectors appears in
// the library source (templates, TypeScript and CSS in projects/ui/src/lib),
// literally or through a dynamic prefix such as `btn-${variant}`. Rules without
// a class (@font-face, :root tokens, element rules, keyframes) are always kept.
// The check only removes rules no component can ever match, so the components
// render the same with either file.
//
//   node tools/gen-core-theme.mjs        (runs as part of npm run build:ui)
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import postcss from 'postcss';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const libDir = join(root, 'projects/ui/src/lib');
const source = join(root, 'projects/ui/src/styles/utilities/DGATheme.css');
const target = join(root, 'projects/ui/src/styles/utilities/DGATheme.core.css');

const walk = (dir) =>
  readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)],
  );

// Every word in the library source, and every prefix used to build a class name.
const words = new Set();
const prefixes = new Set();
for (const file of walk(libDir).filter((f) => /\.(ts|html|css)$/.test(f) && !f.endsWith('.spec.ts'))) {
  const text = readFileSync(file, 'utf8');
  for (const word of text.match(/[A-Za-z][\w-]*/g) ?? []) words.add(word);
  for (const m of text.matchAll(/([A-Za-z][\w-]*-)(?:\$\{|['"`]\s*\+)/g)) prefixes.add(m[1]);
}
const usedClass = (name) => words.has(name) || [...prefixes].some((p) => name.startsWith(p));
const classesOf = (selector) =>
  (selector.replace(/\[[^\]]*\]/g, '').match(/\.[A-Za-z][\w-]*/g) ?? []).map((c) => c.slice(1));
const canMatch = (selector) => classesOf(selector).every(usedClass);

const css = readFileSync(source, 'utf8');
const ast = postcss.parse(css);
let removed = 0;
ast.walkRules((rule) => {
  if (rule.parent?.type === 'atrule' && /keyframes$/i.test(rule.parent.name)) return;
  const keep = rule.selectors.filter(canMatch);
  if (keep.length === 0) {
    rule.remove();
    removed++;
  } else if (keep.length < rule.selectors.length) {
    rule.selectors = keep;
  }
});
// Remove @media / @supports blocks that are now empty (repeat for nested ones).
for (let again = true; again; ) {
  again = false;
  ast.walkAtRules((at) => {
    if (at.nodes && at.nodes.every((n) => n.type === 'comment')) {
      at.remove();
      again = true;
    }
  });
}

const header =
  '/* GENERATED by tools/gen-core-theme.mjs from DGATheme.css. Do not edit by hand.\n' +
  '   The vendored base theme reduced to the rules a library component can match.\n' +
  '   Loaded by mod-core.css. */\n';
writeFileSync(target, header + ast.toString());
console.log(
  `DGATheme.core.css: ${removed} rules removed, ${Math.round(css.length / 1024)} kB -> ` +
    `${Math.round((header.length + ast.toString().length) / 1024)} kB`,
);
